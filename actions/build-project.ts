import { defineAction, fail, noteExternalWrite } from "@agent-native/core/action";
import { getRequestContext } from "@agent-native/core/server";
import { and, desc, eq } from "drizzle-orm";
import { z } from "zod";

import { getDb, schema } from "../server/db/index.js";
import { buildAccessFilter, getBuildAuthUserId } from "../server/lib/build-access.js";
import { serializeBuild } from "../server/lib/build-serialize.js";
import { reapInterrupted, startBuild, waitForBuild } from "../server/lib/builder.js";
import { readDesignPrototypeForIdea } from "../server/lib/design-prototype.js";
import { hackathonLink, nowIso, requireHackathon } from "../server/lib/workspace.js";
import { buildOut } from "../shared/build.js";

const boolParam = z.union([z.boolean(), z.enum(["true", "false"])]);
const starting = new Map<string, Promise<unknown>>();

/** Serialize claims through worker registration. Waiting for a build happens outside this slot. */
async function withStartSlot<T>(hackathonId: string, claim: () => Promise<T>) {
  const previous = starting.get(hackathonId);
  const pending = (previous?.catch(() => undefined) ?? Promise.resolve()).then(claim);
  starting.set(hackathonId, pending);
  try {
    return await pending;
  } finally {
    if (starting.get(hackathonId) === pending) starting.delete(hackathonId);
  }
}

export default defineAction({
  description:
    'Build it: generate and verify a Vite + React + TypeScript starter from the selected idea (or ideaId) and sprint. By default a linked Design prototype guides the UI and the build stays private to its initiator. Pass design="off" to build without Design. Mode "template" uses a deterministic starter without Design or a model. Regular builds update Core works tasks on success. Poll get-build with the returned build ID. If a readable build is already running for the hackathon, returns that run.',
  schema: z.object({
    hackathonId: z.string().describe("Hackathon id"),
    ideaId: z.string().optional().describe("Idea to build; defaults to the selected idea"),
    mode: z
      .enum(["llm", "template"])
      .default("llm")
      .describe('"llm" (default): generated by the build model with repair loop; "template": deterministic starter, no model'),
    design: z
      .enum(["auto", "off"])
      .default("auto")
      .describe('"auto" uses the current user\'s linked prototype in model builds; "off" ignores it'),
    wait: boolParam
      .optional()
      .describe("true to wait up to ~4 minutes for the result instead of returning while it runs"),
  }),
  outputSchema: buildOut,
  persistInChatHistory: false,
  timeoutMs: 300_000,
  link: ({ args }) => hackathonLink(args.hackathonId, "plan"),
  run: async (args, ctx) => {
    const row = await requireHackathon(args.hackathonId, "editor");
    const db = getDb();
    const request = getRequestContext();
    const authUserId = getBuildAuthUserId();
    const userEmail = request?.agentRunAnonymous
      ? undefined
      : request?.userEmail?.trim().toLowerCase();
    const buildId = await withStartSlot(row.id, async () => {
      const active = await reapInterrupted(row.id);
      if (active) return active;
      if (ctx?.signal?.aborted) {
        fail("Build start was canceled.", { errorCode: "build_canceled", statusCode: 409 });
      }
      const [idea] = await db
        .select()
        .from(schema.ideas)
        .where(
          and(
            eq(schema.ideas.hackathonId, row.id),
            args.ideaId ? eq(schema.ideas.id, args.ideaId) : eq(schema.ideas.selected, true),
          ),
        )
        .orderBy(desc(schema.ideas.updatedAt))
        .limit(1);
      if (!idea) {
        fail(
          args.ideaId
            ? "That idea isn't in this hackathon. Call get-hackathon for idea ids."
            : "Pick an idea first (update-idea selected=true), or pass ideaId.",
          { errorCode: "no_idea", statusCode: 400 },
        );
      }
      const prototype = args.mode === "llm" && args.design === "auto" && userEmail
        ? await readDesignPrototypeForIdea(row.id, idea.id, userEmail)
        : null;
      if (prototype && !authUserId) {
        fail("Sign in to build from your private Design prototype.", {
          errorCode: "design_build_sign_in_required",
          statusCode: 401,
        });
      }
      if (ctx?.signal?.aborted) {
        fail("Build start was canceled.", { errorCode: "build_canceled", statusCode: 409 });
      }
      const id = crypto.randomUUID();
      noteExternalWrite("local-disk");
      await db.insert(schema.builds).values({
        id,
        hackathonId: row.id,
        ideaId: idea.id,
        ideaTitle: idea.title,
        status: "running",
        stage: "queued",
        mode: args.mode,
        designPrototypeId: prototype?.id ?? null,
        designOwnerAuthId: prototype ? (authUserId ?? null) : null,
        meta: { source: prototype ? "design" : "idea" },
        steps: [{ at: nowIso(), stage: "queued", label: `Build “${idea.title}”`, status: "info" }],
        ownerEmail: userEmail ?? ctx?.userEmail ?? row.ownerEmail,
        orgId: prototype ? null : row.orgId,
      });
      startBuild(id);
      return id;
    });
    const readableBuild = and(eq(schema.builds.id, buildId), buildAccessFilter(authUserId));
    const [initial] = await db.select().from(schema.builds).where(readableBuild).limit(1);
    if (!initial) {
      fail("A build is already running for this hackathon. Try again when it finishes.", {
        errorCode: "build_busy",
        statusCode: 409,
      });
    }
    if (args.wait !== true && args.wait !== "true") return serializeBuild(initial);
    await waitForBuild(buildId, 240_000);
    const [b] = await db.select().from(schema.builds).where(readableBuild).limit(1);
    if (!b) fail("The build record disappeared.", { errorCode: "not_found", statusCode: 500 });
    return serializeBuild(b);
  },
});
